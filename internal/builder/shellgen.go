func navIcon(route, name string) string {
	hay := strings.ToLower(route + " " + name)
	if route == "/" {
		hay = "home " + hay
	}
	for _, w := range navIconWords {
		if strings.Contains(hay, w[0]) && lucideIcons[w[1]] {
			return w[1]
		}
	}
	return "LayoutGrid"
}

type shellItem struct{ href, label, icon string }

// One nav item per real page, so the shell never links to a route that was not generated.
func shellItems(prd *PRD, react bool) []shellItem {
	var items []shellItem
	if react {
		for _, v := range viewsOf(prd) {
			items = append(items, shellItem{v.Slug, v.Name, navIcon(v.Route, v.Name)})
		}
		return items
	}
	for _, rt := range parsePRDRoutes(prd) {
		name, _, _ := strings.Cut(rt.name, ":")
		name = strings.TrimSpace(name)
		if name == "" {
			name = "Home"
		}
		items = append(items, shellItem{rt.route, name, navIcon(rt.route, name)})
	}
	if len(items) == 0 {
		items = append(items, shellItem{"/", "Home", "Home"})
	}
	return items
}

func shellVariant(prd *PRD) string {
	if prd.Design == nil {
		return "sidebar"
	}
	switch prd.Design.Navigation {
	case "top", "none":
		return "topbar"
	case "bottom":
		return "bottom"
	}
	return "sidebar"
}

func brandIcon(prd *PRD) string {
	if prd.Design != nil && lucideIcons[prd.Design.BrandIcon] {
		return prd.Design.BrandIcon
	}
	return "Sparkles"
}

var jsString = regexp.MustCompile(`[\\"\n\r<>]`)

// A double-quoted JS string that cannot break out of the file it is written into.
func jsQuote(s string) string {
	return `"` + jsString.ReplaceAllStringFunc(s, func(c string) string {
		switch c {
		case "\n", "\r":
			return " "
		case "<":
			return `\x3c`
		case ">":
			return `\x3e`
		}
		return `\` + c
	}) + `"`
}

func shellImports(items []shellItem, brand string) string {
	seen := map[string]bool{brand: true}
	names := []string{brand}
	for _, it := range items {
		if !seen[it.icon] {
			seen[it.icon] = true
			names = append(names, it.icon)
		}
	}
	sort.Strings(names)
	return strings.Join(names, ", ")
}

// Next.js: the app frame around every page, written by the server from the routes and the design direction.
func writeNextShell(workdir string, prd *PRD) error {
	items := shellItems(prd, false)
	brand := brandIcon(prd)
	var nav []string
	for _, it := range items {
		nav = append(nav, fmt.Sprintf("  { href: %s, label: %s, icon: %s },", jsQuote(it.href), jsQuote(it.label), it.icon))
	}
	src := fmt.Sprintf(`"use client";

// Generated by Build mode from the app's pages and design direction; the layout itself lives in @/components/blocks.
import * as React from "react";
import Link from "next/link";
import { usePathname } from "next/navigation";
import { %s } from "lucide-react";
import { AppShell as Shell, type NavItem } from "@/components/blocks";

const nav: NavItem[] = [
%s
];

export function AppShell({ children, actions }: { children: React.ReactNode; actions?: React.ReactNode }) {
  const pathname = usePathname() || "/";
  return (
    <Shell brand={%s} brandIcon={%s} nav={nav} current={pathname} variant=%q linkComponent={Link} actions={actions}>
      {children}
    </Shell>
  );
}
`, shellImports(items, brand), strings.Join(nav, "\n"), jsQuote(prd.Name), brand, shellVariant(prd))
	return writeFile(workdir, "components/app/app-shell.tsx", src)
}

// React + Vite: the same frame, switching views by state instead of routes.
func writeReactFrame(workdir string, prd *PRD) error {
	items := shellItems(prd, true)
	brand := brandIcon(prd)
	var nav []string
	for _, it := range items {
		nav = append(nav, fmt.Sprintf("  { href: %s, label: %s, icon: %s },", jsQuote(it.href), jsQuote(it.label), it.icon))
	}
	src := fmt.Sprintf(`// Generated by Build mode from the app's views and design direction; the layout itself lives in @/components/blocks.
import { %s } from "lucide-react";
import { AppShell } from "@/components/blocks";

const nav = [
%s
];

export function AppFrame({ view, setView, actions, children }) {
  return (
    <AppShell brand={%s} brandIcon={%s} nav={nav} current={view} onNavigate={setView} variant=%q actions={actions}>
      {children}
    </AppShell>
  );
}
`, shellImports(items, brand), strings.Join(nav, "\n"), jsQuote(prd.Name), brand, shellVariant(prd))
	return writeFile(workdir, "src/components/app/AppFrame.jsx", src)
}

func writeFile(workdir, rel, content string) error {
	abs := filepath.Join(workdir, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(abs), 0755); err != nil {
		return err
	}
	return os.WriteFile(abs, []byte(content), 0644)
}

