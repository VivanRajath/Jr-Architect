// This screen's plan from the design direction, as prompt text.
func screenPlan(prd *PRD, route string) string {
	if prd.Design == nil {
		return ""
	}
	for _, s := range prd.Design.Screens {
		if staticRoute(strings.TrimSpace(s.Route)) == route || (route == "/" && (s.Route == "home" || s.Route == "")) {
			var b strings.Builder
			fmt.Fprintf(&b, "\nSCREEN PLAN for %s (decided by the art director; build exactly this layout):\n- Layout: %s\n", route, s.Layout)
			for _, sec := range s.Sections {
				fmt.Fprintf(&b, "- %s\n", sec)
			}
			return b.String()
		}
	}
	return ""
}
